// Helper function to determine status level
const getStatusLevel = (status: string): number => {
  if (!status) return 1;
  const lowerStatus = status.toLowerCase();
  if (lowerStatus === 'confirmed') return 5;
  if (lowerStatus === 'pending') return 3;
  if (lowerStatus.includes('canceled') || lowerStatus.includes('cancelled')) return 1;
  if (lowerStatus === 'accepted') return 4;
  if (lowerStatus === 'in transit') return 6;
  if (lowerStatus === 'delivered') return 7;
  if (lowerStatus === 'closed') return 6;
  if (lowerStatus === 'draft') return 1;
  if (lowerStatus === 'requested') return 2;
  return 2;
};

// Helper function to parse date
const parseDate = (dateStr: string): string => {
  if (!dateStr || dateStr === '--' || dateStr === 'TBD') return '--:--';
  
  // Handle different date formats
  if (dateStr.includes('-')) {
    // Format like "24-Jun" or "01-Jul"
    const parts = dateStr.split('-');
    if (parts.length === 2) {
      const day = parts[0];
      const month = parts[1];
      return `${month} ${day}, 2025`;
    }
  }
  
  return dateStr;
};

// Helper function to combine vessel and voyage
const combineVesselVoyage = (vessel: string, voyage: string): string => {
  if (!vessel && !voyage) return 'no vessel';
  if (!vessel) return voyage;
  if (!voyage) return vessel;
  return `${vessel} ${voyage}`.trim();
};

